#!/usr/bin/env python3
"""Builds single-file/campus_connect_all_in_one.cpp from src/, tests/ and app/.

Use the single file in an online C++17 compiler when you have no compiler installed.
Run from the repo root:  python3 tools/make_single_file.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORDER = [
    "src/models.hpp",
    "src/email_provider.hpp", "src/email_provider.cpp",
    "src/sms_gateway.hpp", "src/sms_gateway.cpp",
    "src/campus_admin_api.hpp",
    "src/registration_service.hpp", "src/registration_service.cpp",
    "src/kiosk.hpp", "src/kiosk.cpp",
    "tests/mini_test.hpp",
    "tests/test_rig.hpp",
    "tests/baseline_tests.cpp",
    "tests/change_card_tests.cpp",
    "app/main.cpp",
]
LOCAL_INCLUDE = re.compile(r'^\s*#include\s+"[^"]+"\s*$')
STD_INCLUDE = re.compile(r'^\s*#include\s+<([^>]+)>\s*$')

std_headers = set()
bodies = []
for rel in ORDER:
    lines = (ROOT / rel).read_text(encoding="utf-8").splitlines()
    kept = []
    for line in lines:
        if line.strip() == "#pragma once" or LOCAL_INCLUDE.match(line):
            continue
        match = STD_INCLUDE.match(line)
        if match:
            std_headers.add(match.group(1))
            continue
        kept.append(line)
    text = "\n".join(kept).strip("\n")
    if rel == "app/main.cpp":
        text = text.replace("int main() {", "static int runDemo() {")
    bodies.append(f"// ===================== {rel} =====================\n{text}\n")

header = (
    "// campus_connect_all_in_one.cpp - GENERATED by tools/make_single_file.py\n"
    "// The whole CampusConnect starter in ONE file, for online C++17 compilers.\n"
    "// Paste it all, choose C++17, press Run. It runs the tests, then the demo.\n"
    "// If you change code here, submit THIS file (see SUBMISSION.md).\n\n"
)
includes = "\n".join(f"#include <{h}>" for h in sorted(std_headers))
footer = (
    "// ===================== single-file main =====================\n"
    "int main() {\n"
    "    const int result = mini_test::runAll();\n"
    '    std::cout << "\\n---------- demo ----------\\n";\n'
    "    runDemo();\n"
    "    return result;\n"
    "}\n"
)
out = ROOT / "single-file" / "campus_connect_all_in_one.cpp"
out.parent.mkdir(exist_ok=True)
out.write_text(header + includes + "\n\n" + "\n".join(bodies) + "\n" + footer, encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)}")
